#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import { getTunnelPort, loadRegistry, REPO_ROOT } from './lib/registry.mjs'

const OUT_PATH = path.join(REPO_ROOT, 'web/frontend/src/utils/integrationPorts.generated.ts')

function main() {
  const registry = loadRegistry()
  const lines = []

  lines.push('/**')
  lines.push(' * AUTO-GENERATED by scripts/gen-integration-ports.mjs')
  lines.push(' * Source: docs/integration/ports.registry.yaml')
  lines.push(' * Do not edit manually. Run: node scripts/gen-integration-ports.mjs')
  lines.push(' */')
  lines.push('')
  lines.push(`export const INTEGRATION_HOST = '${registry.host}' as const`)
  lines.push('')
  lines.push('export const platformPorts = {')
  lines.push(`  frontend: ${registry.platform.frontend_port},`)
  lines.push(`  backend: ${registry.platform.backend_port},`)
  lines.push('} as const')
  lines.push('')
  lines.push(`export const tunnelOffset = ${registry.tunnel_offset} as const`)
  lines.push('')

  const uiSystems = registry.systems.filter((system) => Number.isFinite(system.ui_port))
  const systemIds = uiSystems.map((s) => s.id)
  lines.push('export type IntegrationSystemPortId =')
  systemIds.forEach((id, index) => {
    lines.push(`  | '${id}'${index === systemIds.length - 1 ? '' : ''}`)
  })
  lines.push('')
  lines.push('export interface SystemPortEntry {')
  lines.push('  ui: number')
  lines.push('  api?: number')
  lines.push('  tunnel: number')
  lines.push('  integrationStatus: string')
  lines.push('}')
  lines.push('')
  lines.push('export const systemPorts: Record<IntegrationSystemPortId, SystemPortEntry> = {')

  for (const system of uiSystems) {
    const api = system.api_port != null ? `, api: ${system.api_port}` : ''
    lines.push(
      `  '${system.id}': { ui: ${system.ui_port}${api}, tunnel: ${getTunnelPort(registry, system.ui_port)}, integrationStatus: '${system.integration_status}' },`,
    )
  }

  lines.push('}')
  lines.push('')
  lines.push('export function getSystemUiUrl(')
  lines.push('  systemId: IntegrationSystemPortId,')
  lines.push(`  host: string = INTEGRATION_HOST,`)
  lines.push('): string {')
  lines.push('  const entry = systemPorts[systemId]')
  lines.push('  if (!entry) {')
  lines.push("    throw new Error(`Unknown integration system port id: ${systemId}`)")
  lines.push('  }')
  lines.push('  return `http://${host}:${entry.ui}`')
  lines.push('}')
  lines.push('')
  lines.push('export function getSystemApiUrl(')
  lines.push('  systemId: IntegrationSystemPortId,')
  lines.push(`  host: string = INTEGRATION_HOST,`)
  lines.push('): string | undefined {')
  lines.push('  const entry = systemPorts[systemId]')
  lines.push('  if (!entry?.api) {')
  lines.push('    return undefined')
  lines.push('  }')
  lines.push('  return `http://${host}:${entry.api}`')
  lines.push('}')
  lines.push('')
  lines.push('export function getTunnelLocalPort(uiPort: number, offset: number = tunnelOffset): number {')
  lines.push('  return offset + uiPort')
  lines.push('}')

  fs.writeFileSync(path.resolve(OUT_PATH), `${lines.join('\n')}\n`, 'utf8')
  console.log(`Wrote ${OUT_PATH}`)
}

main()
